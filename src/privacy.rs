//! Decides whether a clipboard snapshot may be recorded, and builds the item.

use crate::config::Config;
use crate::store::NewItem;

pub const CONCEALED: &str = "org.nspasteboard.ConcealedType";
pub const TRANSIENT: &str = "org.nspasteboard.TransientType";
pub const AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";

/// Everything read from the pasteboard for one change.
#[derive(Debug, Clone, Default)]
pub struct Snapshot {
    pub types: Vec<String>,
    pub text: Option<String>,
    pub rtf: Option<Vec<u8>>,
    pub html: Option<Vec<u8>>,
    /// PNG-encoded image (converted from TIFF by the platform layer if needed).
    pub image_png: Option<Vec<u8>>,
    pub thumb_png: Option<Vec<u8>>,
}

#[derive(Debug, PartialEq, Eq)]
pub enum Skip {
    Sensitive,
    ExcludedApp,
    TooLarge,
    Empty,
}

/// Apply the privacy/size rules and turn a snapshot into a storable item.
pub fn build_item(
    snap: Snapshot,
    frontmost_bundle: Option<&str>,
    frontmost_name: Option<&str>,
    cfg: &Config,
) -> Result<NewItem, Skip> {
    if snap
        .types
        .iter()
        .any(|t| t == CONCEALED || t == TRANSIENT || t == AUTO_GENERATED)
    {
        return Err(Skip::Sensitive);
    }
    if let Some(b) = frontmost_bundle
        && cfg
            .excluded_bundle_ids
            .iter()
            .any(|x| x.eq_ignore_ascii_case(b))
    {
        return Err(Skip::ExcludedApp);
    }
    let text = snap.text.filter(|t| !t.is_empty());
    if let Some(t) = &text
        && t.len() > cfg.max_text_bytes
    {
        return Err(Skip::TooLarge);
    }
    if let Some(i) = &snap.image_png
        && i.len() > cfg.max_image_bytes
    {
        return Err(Skip::TooLarge);
    }
    let rtf = snap.rtf.filter(|b| b.len() <= cfg.max_text_bytes);
    let html = snap.html.filter(|b| b.len() <= cfg.max_text_bytes);
    // Text copied together with an image (e.g. from a web page) is kept as text.
    let (image_png, thumb_png) = if text.is_none() {
        (snap.image_png, snap.thumb_png)
    } else {
        (None, None)
    };
    if text.is_none() && image_png.is_none() {
        return Err(Skip::Empty);
    }
    Ok(NewItem {
        text,
        rtf,
        html,
        image_png,
        thumb_png,
        source_app: frontmost_name.map(str::to_string),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn text_snap(t: &str) -> Snapshot {
        Snapshot {
            types: vec!["public.utf8-plain-text".into()],
            text: Some(t.into()),
            ..Default::default()
        }
    }

    #[test]
    fn plain_text_is_captured() {
        let it = build_item(
            text_snap("hello"),
            Some("com.apple.Safari"),
            Some("Safari"),
            &Config::default(),
        )
        .unwrap();
        assert_eq!(it.text.as_deref(), Some("hello"));
        assert_eq!(it.source_app.as_deref(), Some("Safari"));
    }

    #[test]
    fn concealed_transient_and_auto_generated_are_dropped() {
        for marker in [CONCEALED, TRANSIENT, AUTO_GENERATED] {
            let mut s = text_snap("secret");
            s.types.push(marker.into());
            assert_eq!(
                build_item(s, None, None, &Config::default()).unwrap_err(),
                Skip::Sensitive
            );
        }
    }

    #[test]
    fn excluded_app_is_dropped() {
        let r = build_item(
            text_snap("x"),
            Some("com.bitwarden.desktop"),
            Some("Bitwarden"),
            &Config::default(),
        );
        assert_eq!(r.unwrap_err(), Skip::ExcludedApp);
    }

    #[test]
    fn oversized_text_and_image_are_dropped() {
        let cfg = Config {
            max_text_bytes: 4,
            max_image_bytes: 4,
            ..Config::default()
        };
        assert_eq!(
            build_item(text_snap("12345"), None, None, &cfg).unwrap_err(),
            Skip::TooLarge
        );
        let s = Snapshot {
            image_png: Some(vec![0; 5]),
            ..Default::default()
        };
        assert_eq!(build_item(s, None, None, &cfg).unwrap_err(), Skip::TooLarge);
    }

    #[test]
    fn image_only_is_captured_and_empty_is_skipped() {
        let s = Snapshot {
            image_png: Some(vec![1, 2, 3]),
            thumb_png: Some(vec![9]),
            ..Default::default()
        };
        let it = build_item(s, None, None, &Config::default()).unwrap();
        assert!(it.image_png.is_some() && it.text.is_none());
        assert_eq!(
            build_item(Snapshot::default(), None, None, &Config::default()).unwrap_err(),
            Skip::Empty
        );
    }

    #[test]
    fn rich_text_keeps_all_representations() {
        let s = Snapshot {
            text: Some("hi".into()),
            rtf: Some(b"rtf".to_vec()),
            html: Some(b"<b>".to_vec()),
            ..Default::default()
        };
        let it = build_item(s, None, None, &Config::default()).unwrap();
        assert!(it.rtf.is_some() && it.html.is_some());
    }
}
